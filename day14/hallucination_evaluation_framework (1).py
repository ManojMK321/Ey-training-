from openai import OpenAI
from wikipediaapi import Wikipedia

class RetrievalManager:
    def __init__(self, agent_name: str = "HallucinationEval/1.0"):
        self.wiki = Wikipedia(agent_name, "en")

    def get_evidence(self, query: str, top_k: int = 3) -> str:
        page = self.wiki.page(query)
        if page.exists():
            return page.summary[:2000] # Limit context size
        return "No specific evidence found."

class FactScoreEvaluator:
    def __init__(self, model: str = "gpt-4o-mini"):
        self.client = OpenAI()
        self.model = model
        self.retriever = RetrievalManager()

    def extract_claims(self, text: str) -> List[str]:
        sentences = nltk.sent_tokenize(text)
        return [s.strip() for s in sentences if len(s.strip()) > 10]

    def verify_claim(self, claim: str, evidence: str) -> str:
        prompt = f"Claim: {claim}\nEvidence: {evidence}\nDetermine if the evidence supports the claim. Return ONLY 'SUPPORTED' or 'UNSUPPORTED'."
        response = self.client.chat.completions.create(
            model=self.model,
            messages=[{"role": "user", "content": prompt}],
            temperature=0
        )
        res = response.choices[0].message.content.strip().upper()
        return "SUPPORTED" if "SUPPORTED" in res else "UNSUPPORTED"

    def evaluate(self, question: str, generated_answer: str) -> Dict[str, Any]:
        claims = self.extract_claims(generated_answer)
        if not claims: return {"factscore": 0.0, "supported": 0, "total": 0}

        evidence = self.retriever.get_evidence(question)
        results = [self.verify_claim(c, evidence) for c in claims]
        supported = results.count("SUPPORTED")

        return {
            "factscore": supported / len(claims),
            "supported_claims": supported,
            "total_claims": len(claims),
            "details": list(zip(claims, results))
        }

from transformers import AutoModelForSequenceClassification, AutoTokenizer
import torch
import torch.nn.functional as F

class HHEMEvaluator:
    def __init__(self, model_id: str = "vectara/hallucination_evaluation_model"):
        # Using AutoModelForSequenceClassification as recommended for HHEM
        self.tokenizer = AutoTokenizer.from_pretrained(model_id, trust_remote_code=True)
        self.model = AutoModelForSequenceClassification.from_pretrained(model_id, trust_remote_code=True)
        self.device = "cuda" if torch.cuda.is_available() else "cpu"
        self.model.to(self.device)
        self.model.eval()

    def evaluate(self, reference: str, generated: str) -> Dict[str, Any]:
        inputs = self.tokenizer(reference, generated, return_tensors="pt", truncation=True, max_length=512).to(self.device)

        with torch.no_grad():
            outputs = self.model(**inputs)

        # HHEM-v2 specifically uses the logits for binary classification
        logits = outputs.logits
        probs = F.softmax(logits, dim=-1)

        # Index 1 is usually the 'faithful' probability for this model
        faith_prob = probs[0][1].item()

        return {
            "hallucination_probability": 1 - faith_prob,
            "faithfulness_probability": faith_prob,
            "label": "hallucinated" if faith_prob < 0.5 else "non_hallucinated"
        }

from bert_score import score

class BERTScoreEvaluator:
    def evaluate(self, reference: str, generated: str) -> Dict[str, Any]:
        P, R, F1 = score([generated], [reference], lang="en", verbose=False)
        return {
            "precision": P.item(),
            "recall": R.item(),
            "f1": F1.item()
        }

from sentence_transformers import SentenceTransformer, util

class SelfCheckGPTEvaluator:
    def __init__(self, model: str = "gpt-4o-mini"):
        self.client = OpenAI()
        self.model = model
        self.embedder = SentenceTransformer('all-MiniLM-L6-v2')

    def evaluate(self, question: str, generated_answer: str, n: int = 5) -> Dict[str, Any]:
        samples = []
        for _ in range(n):
            resp = self.client.chat.completions.create(
                model=self.model,
                messages=[{"role": "user", "content": question}],
                temperature=1.0
            )
            samples.append(resp.choices[0].message.content)

        main_emb = self.embedder.encode(generated_answer, convert_to_tensor=True)
        sample_embs = self.embedder.encode(samples, convert_to_tensor=True)
        cos_sim = util.cos_sim(main_emb, sample_embs).mean().item()

        return {
            "mean_similarity": cos_sim,
            "hallucination_risk": 1 - cos_sim,
            "samples": samples
        }

class HallucinationEvaluationPipeline:
    def __init__(self):
        self.fs = FactScoreEvaluator()
        self.hhem = HHEMEvaluator()
        self.bs = BERTScoreEvaluator()
        self.sc = SelfCheckGPTEvaluator()

    def run(self, question: str, generated: str, reference: str) -> Dict[str, Any]:
        f_res = self.fs.evaluate(question, generated)
        h_res = self.hhem.evaluate(reference, generated)
        b_res = self.bs.evaluate(reference, generated)
        s_res = self.sc.evaluate(question, generated)

        # Weighted Index Calculation
        # Formula: 0.35*(1-FS) + 0.30*(1-HHEM_faith) + 0.20*(1-BS_F1) + 0.15*SC_Risk
        idx = (0.35 * (1 - f_res['factscore'])) + \
              (0.30 * (1 - h_res['hallucination_probability'])) + \
              (0.20 * (1 - b_res['f1'])) + \
              (0.15 * s_res['hallucination_risk'])

        return {
            "factscore": f_res,
            "hhem": h_res,
            "bertscore": b_res,
            "selfcheck": s_res,
            "hallucination_index": np.clip(idx, 0, 1)
        }

